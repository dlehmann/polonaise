#!/usr/bin/env python3
"""
music.py - the music and the sound effects of Polonaise C64 for the SID, after
tools/polonaise-sounds.py of the arcade cabinet: a disco loop of 16 bars at 120 bpm
(four on the floor, claps on 2 and 4, open hi-hats on the off-beats, an octave bass,
chord stabs in bars 1..8 and the lead melody in bars 9..16) and the effects.

The music is written as one event per 16th note and voice (256 steps). Voice 1 plays
the bass through the low pass filter, voice 2 the drums, voice 3 the stabs and the
melody; the effects take voice 3 while they play.

Output: gen/music.inc

Usage: tools/music.py <gen dir>
"""
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else 'gen'
PAL_CLOCK, NTSC_CLOCK = 985248, 1022727
A4 = 69

lines = ['; generated by tools/music.py']


def table(name, values):
    lines.append('%s:' % name)
    for i in range(0, len(values), 16):
        lines.append('    .byte ' + ','.join(str(v) for v in values[i:i + 16]))


def const(name, v):
    lines.append('%s = %d' % (name, v))


def hz(f, clock):
    return min(0xffff, int(round(f * 16777216 / clock)))


def note_hz(n):
    return 440.0 * 2 ** ((n - 69) / 12)


# note frequencies for MIDI notes 0..107 (PAL and NTSC)
for name, clock in (('pal', PAL_CLOCK), ('ntsc', NTSC_CLOCK)):
    f = [hz(note_hz(n), clock) for n in range(108)]
    table('freq_lo_' + name, [v & 255 for v in f])
    table('freq_hi_' + name, [v >> 8 for v in f])

# ---------------------------------------------------------------- music

STEPS = 256
bass = [0] * STEPS          # 0 none, else MIDI note (gate on for 6 ticks)
drum = [0] * STEPS          # 0 none, 1 kick, 2 kick + clap, 3 closed hat, 4 open hat
v3 = [0] * STEPS            # 0 none, 1..: chord (stab) index + 1 with $80, else melody note; length in v3len
v3len = [0] * STEPS

prog = [(45, [57, 60, 64]), (45, [57, 60, 64]), (50, [57, 62, 65]), (50, [57, 62, 65]),
        (43, [55, 59, 62]), (43, [55, 59, 62]), (48, [55, 60, 64]), (52, [56, 59, 64])] * 2
chords = []
for bar in range(16):
    root, chord = prog[bar]
    s0 = bar * 16
    for beat in range(4):
        s = s0 + beat * 4
        drum[s] = 2 if beat in (1, 3) else 1
        drum[s + 1] = 3
        drum[s + 2] = 4
        drum[s + 3] = 3
    for e in range(8):
        bass[s0 + e * 2] = root - 12 + (12 if e % 2 else 0)
    if bar < 8:
        if chord not in chords:
            chords.append(chord)
        for st in (6, 14):
            v3[s0 + st] = 0x80 | chords.index(chord)
            v3len[s0 + st] = 2

melody = [
    (0, 76, 1), (1, 76, 0.5), (1.5, 74, 0.5), (2, 72, 1), (3, 69, 1),
    (4, 72, 0.5), (4.5, 74, 0.5), (5, 76, 1), (6, 72, 2),
    (8, 74, 1), (9, 74, 0.5), (9.5, 72, 0.5), (10, 69, 1), (11, 65, 1),
    (12, 69, 0.5), (12.5, 72, 0.5), (13, 74, 1), (14, 69, 2),
    (16, 71, 1), (17, 74, 0.5), (17.5, 71, 0.5), (18, 67, 1), (19, 71, 1),
    (20, 72, 0.5), (20.5, 74, 0.5), (21, 76, 1), (22, 79, 2),
    (24, 76, 1), (25, 72, 0.5), (25.5, 69, 0.5), (26, 71, 1), (27, 68, 1),
    (28, 71, 1), (29, 74, 1), (30, 76, 2),
]
for beat, n, length in melody:
    s = 128 + int(beat * 4)
    v3[s] = n
    v3len[s] = max(1, int(length * 4 * 0.9 + 0.5))

table('mus_bass', bass)
table('mus_drum', drum)
table('mus_v3', v3)
table('mus_v3len', v3len)
table('mus_chord1', [c[0] for c in chords])
table('mus_chord2', [c[1] for c in chords])
table('mus_chord3', [c[2] for c in chords])

# ---------------------------------------------------------------- effects

# commands of an effect program (one per tick unless noted)
ADSR, PW, NOTE, FREQ, SLIDE, OFF, END = 1, 2, 3, 4, 5, 6, 0
TRI, SAW, PULSE, NOISE = 0x11, 0x21, 0x41, 0x81

effects = {}


def f16(f):
    return hz(f, PAL_CLOCK)


def note(n, ticks, wave=TRI):
    return [NOTE, wave, n, ticks]


def freq(f, ticks, wave):
    v = f16(f)
    return [FREQ, wave, v >> 8, v & 255, ticks]


def slide(f0, f1, ticks, wave):
    a, b = f16(f0), f16(f1)
    d = int(round((b - a) / ticks)) & 0xffff
    return [SLIDE, wave, a >> 8, a & 255, d >> 8, d & 255, ticks]


def off(ticks):
    return [OFF, ticks]


def adsr(ad, sr):
    return [ADSR, ad, sr]


def pw(v):
    return [PW, v & 255, v >> 8]


effects['TURN'] = adsr(0x00, 0x30) + freq(2200, 1, TRI) + off(1)
effects['GO'] = adsr(0x00, 0x90) + slide(700, 1800, 11, TRI) + off(3)
effects['DENY'] = adsr(0x00, 0xa0) + pw(0x800) + freq(220, 2, PULSE) + freq(232, 3, PULSE) + off(2)
for k in range(1, 6):
    base = A4 + 3 + 2 * (k - 1)
    effects['CATCH%d' % k] = (adsr(0x00, 0xa0) + freq(3000, 1, NOISE) + adsr(0x09, 0x00) + note(base, 3) + off(1)
                              + note(base + 7, 13) + off(4))
effects['CATCH_STAR'] = (adsr(0x0a, 0x00) + pw(0x400) + note(A4 + 12, 2) + note(A4 + 16, 2) + note(A4 + 19, 3)
                         + note(A4 + 24, 3) + note(A4 + 28, 2) + off(1) + note(A4 + 7, 4, PULSE)
                         + note(A4 + 12, 14, PULSE) + off(4))
effects['FLEE'] = adsr(0x00, 0x80) + pw(0x800) + slide(1600, 2600, 4, PULSE) + off(2)
effects['STAR'] = adsr(0x08, 0x00) + sum((note(n, 2) for n in (A4 + 19, A4 + 24, A4 + 28, A4 + 31)), []) + \
    note(A4 + 36, 10) + off(3)
effects['STAR_GONE'] = adsr(0x08, 0x00) + sum((note(n, 3) for n in (A4 + 31, A4 + 28, A4 + 24)), []) + \
    note(A4 + 19, 10) + off(3)
scratch = []
for fh in (0x0c, 0x30, 0x08, 0x26, 0x05, 0x1c, 0x04, 0x12):
    scratch += [FREQ, NOISE, fh, 0, 2]
effects['CRASH'] = adsr(0x00, 0xf0) + scratch + adsr(0x0a, 0x00) + slide(140, 50, 18, TRI) + off(6)
effects['EXTRA_LIFE'] = (adsr(0x00, 0xa0) + pw(0x800) + sum((note(n, 4, PULSE) for n in
                                                              (A4 + 3, A4 + 7, A4 + 10, A4 + 15)), [])
                         + note(A4 + 19, 10, PULSE) + adsr(0x09, 0x00) + note(A4 + 19, 3) + note(A4 + 22, 3)
                         + note(A4 + 27, 3) + note(A4 + 31, 16) + off(4))
effects['SONG_START'] = (adsr(0x00, 0xa0) + freq(2300, 5, TRI) + off(3) + freq(2300, 5, TRI) + off(3)
                         + sum((freq(2300 + d, 3, TRI) for d in (0, 40, 0, -40, 0, 40, 0)), []) + off(4))
fan = [A4, A4 + 4, A4 + 7, A4 + 12, None, A4 + 7, A4 + 12]
seq = adsr(0x00, 0xa0) + pw(0x800)
for i, n in enumerate(fan):
    if n is None:
        seq += off(5)
    else:
        seq += note(n, 16 if i == len(fan) - 1 else 4, PULSE) + off(1)
effects['CLEARED'] = seq + adsr(0x09, 0x00) + note(A4 + 24, 3) + note(A4 + 28, 3) + note(A4 + 31, 20) + off(4)
effects['GAME_OVER'] = adsr(0x00, 0xaa) + pw(0x800) + slide(note_hz(A4), note_hz(A4 - 24), 84, PULSE) + off(20)
effects['PAUSE'] = adsr(0x00, 0xa0) + note(A4 + 7, 4) + note(A4, 4) + off(3)

names = ['TURN', 'GO', 'DENY', 'CATCH1', 'CATCH2', 'CATCH3', 'CATCH4', 'CATCH5', 'CATCH_STAR', 'FLEE', 'STAR',
         'STAR_GONE', 'CRASH', 'EXTRA_LIFE', 'SONG_START', 'CLEARED', 'GAME_OVER', 'PAUSE']
def length(prog):
    """The ticks an effect plays."""
    i, n = 0, 0
    while i < len(prog):
        c = prog[i]
        size = {ADSR: 3, PW: 3, NOTE: 4, FREQ: 5, SLIDE: 7, OFF: 2}[c]
        n += prog[i + size - 1] if c in (NOTE, FREQ, SLIDE, OFF) else 0
        i += size
    return n


for i, n in enumerate(names):
    const('SFX_' + n, i)
    table('sfx_%d' % i, effects[n] + [END])
table('sfx_len', [min(255, length(effects[n])) for n in names])
lines.append('sfx_lo: .byte ' + ','.join('<sfx_%d' % i for i in range(len(names))))
lines.append('sfx_hi: .byte ' + ','.join('>sfx_%d' % i for i in range(len(names))))
for k, v in (('ADSR', ADSR), ('PW', PW), ('NOTE', NOTE), ('FREQ', FREQ), ('SLIDE', SLIDE), ('OFF', OFF),
             ('END', END)):
    const('SC_' + k, v)

open(os.path.join(OUT, 'music.inc'), 'w').write('\n'.join(lines) + '\n')
