PLACEHOLDERS = {'{song}': 0xf0, '{target}': 0xf1, '{count}': 0xf2, '{rank}': 0xf3, '{score}': 0xf4}


def encode(s, mini):
    out = []
    i = 0
    while i < len(s):
        if s[i] == '{':
            j = s.index('}', i)
            out.append(PLACEHOLDERS[s[i:j + 1]])
            i = j + 1
            continue
        ch = s[i]
        if mini:
            out.append(MINI.index(ch))
        else:
            out.append(CODES[ch])
        i += 1
    out.append(0xff)
    return out


lines = ['; generated by tools/text.py']
names = list(TEXTS)
for i, name in enumerate(names):
    lines.append('T_%s = %d' % (name.replace('.', '_').upper(), i))
lines.append('TEXT_COUNT = %d' % len(names))
for lang, suffix in ((0, 'de'), (1, 'en')):
    for i, name in enumerate(names):
        data = encode(TEXTS[name][lang], name.startswith('mini.'))
        lines.append('text_%s_%d: .byte %s' % (suffix, i, ','.join(str(v) for v in data)))
for part in ('lo', 'hi'):
    lines.append('text_ptr_%s:' % part)
    for suffix in ('de', 'en'):
        lines.append('    .byte ' + ','.join('%s(text_%s_%d)' % ('<' if part == 'lo' else '>', suffix, i)
                                          for i in range(len(names))))
# the codes of characters the code needs
for ch, name in ((' ', 'SPACE'), ('0', 'ZERO'), ('A', 'A'), ('X', 'X'), ('/', 'SLASH'), ('.', 'DOT'),
                 ('?', 'QUESTION'), ('-', 'MINUS'), ('!', 'EXCL'), ('+', 'PLUS'), ('Ä', 'AE'), ('Ö', 'OE'),
                 ('Ü', 'UE'), (':', 'COLON')):
    lines.append('C_%s = %d' % (name, CODES[ch]))
lines.append('M_PLUS = %d' % MINI.index('+'))
lines.append('M_ZERO = %d' % MINI.index('0'))
lines.append('M_X = %d' % MINI.index('X'))
lines.append('M_EXCL = %d' % MINI.index('!'))
lines.append('M_SPACE = %d' % MINI.index(' '))
open(os.path.join(OUT, 'text.inc'), 'w').write('\n'.join(lines) + '\n')
